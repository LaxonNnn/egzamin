create table public.exam_issue_reports (
  id bigint generated by default as identity primary key,
  question_id uuid not null references public.exam_questions(id) on delete cascade,
  reporter_id uuid not null references auth.users(id) on delete cascade,
  report_type text not null check (report_type in ('outdated','wrong','comment')),
  active boolean not null default true,
  comment text,
  created_at timestamptz not null default now(),
  display_name text
);
alter table public.exam_issue_reports enable row level security;
grant select on public.exam_issue_reports to anon;
grant select, insert, update on public.exam_issue_reports to authenticated;
grant usage, select on sequence public.exam_issue_reports_id_seq to authenticated;
create policy "Public can read active exam comments" on public.exam_issue_reports for select to anon, authenticated using (report_type='comment' and active=true and comment is not null);
create policy "Users can create own exam report events" on public.exam_issue_reports for insert to authenticated with check (reporter_id=(select auth.uid()) and (comment is null or char_length(comment)<=180));
create policy "Users can read own exam report history" on public.exam_issue_reports for select to authenticated using (reporter_id=(select auth.uid()) or (select coalesce(auth.jwt()->'app_metadata'->>'role',''))='admin');
create policy "Users can update own exam report" on public.exam_issue_reports for update to authenticated using (reporter_id=(select auth.uid())) with check (reporter_id=(select auth.uid()));
create policy "Admins can update exam report status" on public.exam_issue_reports for update to authenticated using ((select coalesce(auth.jwt()->'app_metadata'->>'role',''))='admin') with check ((select coalesce(auth.jwt()->'app_metadata'->>'role',''))='admin');
create index exam_issue_reports_question_id_idx on public.exam_issue_reports(question_id);
create index exam_issue_reports_reporter_id_idx on public.exam_issue_reports(reporter_id);
create index exam_issue_reports_active_idx on public.exam_issue_reports(active) where active=true;
